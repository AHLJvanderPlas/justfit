#!/usr/bin/env node
/**
 * Generate migrations/0124_exercise_name_nl.sql from scripts/fixtures/exercise-names-nl.json
 * (builder v1.5, BUILDER_UX_PLAN_2026-10.md §5 part A).
 *
 * The JSON is the reviewed source: { "<slug>": "<Dutch name>" } for every active global
 * exercise. The migration is GENERATED from it, never hand-typed, so the review artefact
 * (docs/exercise-names-nl.md, built from the same JSON) and the database cannot disagree.
 *
 * Checks before writing: every value non-empty, ≤ 40 chars, trimmed, unique
 * (case-insensitive); every key a plausible slug. The dry run (--check) loads the seed
 * baseline into node:sqlite, applies the generated SQL and asserts that exactly
 * Object.keys(json).length rows changed and that no two active global rows share a
 * name_nl — the same rule smoke G2 enforces for `name`.
 *
 * Usage:
 *   node scripts/generate-name-nl-migration.mjs           # writes the migration
 *   node scripts/generate-name-nl-migration.mjs --check   # writes it, then dry-runs it
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';

const SRC = 'scripts/fixtures/exercise-names-nl.json';
const OUT = 'migrations/0124_exercise_name_nl.sql';
const MAX = 40;
const CHECK = process.argv.includes('--check');

const names = JSON.parse(readFileSync(SRC, 'utf8'));
const entries = Object.entries(names);
const errs = [];
const seen = new Map();
for (const [slug, nl] of entries) {
  if (!/^[a-z0-9][a-z0-9-]*$/.test(slug)) errs.push(`bad slug ${slug}`);
  if (typeof nl !== 'string' || !nl.trim()) errs.push(`empty name for ${slug}`);
  else {
    if (nl !== nl.trim()) errs.push(`untrimmed name for ${slug}`);
    if (nl.length > MAX) errs.push(`too long (${nl.length}) ${slug}: ${nl}`);
    const k = nl.toLowerCase();
    if (seen.has(k)) errs.push(`duplicate "${nl}": ${seen.get(k)} / ${slug}`);
    seen.set(k, slug);
  }
}
if (errs.length) { console.error(errs.join('\n')); process.exit(1); }

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const now = Date.now();
const sql = `-- 0124 — Dutch exercise names (builder v1.5, BUILDER_UX_PLAN_2026-10.md §5 part A).
--
-- GENERATED by scripts/generate-name-nl-migration.mjs from
-- scripts/fixtures/exercise-names-nl.json (${entries.length} active global rows); the review
-- table docs/exercise-names-nl.md is built from the same JSON. Do not hand-edit: change the
-- JSON, regenerate, and ship the change as a NEW migration (this one is applied history).
--
-- name_nl existed on the table since the library's first migrations and was empty on every
-- row; the client showed English names to Dutch users and search could not find
-- "opdrukken". Conventions: training-science terms stay English (Plank, Burpee, Dead bug,
-- Cooper test, Zone 2); movements are Dutch (Opdrukken, Optrekken, Uitvalspas, Heupbrug).
-- Only slug-matched, global (gym_id IS NULL) rows are touched; inactive rows keep NULL.
${entries.map(([slug, nl]) => `UPDATE exercises SET name_nl = ${q(nl)}, updated_at_ms = ${now} WHERE slug = ${q(slug)} AND gym_id IS NULL AND is_active = 1;`).join('\n')}
`;
writeFileSync(OUT, sql);
console.log(`wrote ${OUT}: ${entries.length} UPDATE statements`);

if (CHECK) {
  const db = new DatabaseSync(':memory:');
  for (const f of ['1010_schema_training.sql', '1000_schema_core.sql', '1020_seed_exercises.sql']) db.exec(readFileSync(`migrations/baseline/${f}`, 'utf8'));
  const before = db.prepare("SELECT count(*) AS n FROM exercises WHERE is_active = 1 AND gym_id IS NULL").get().n;
  db.exec(sql);
  const filled = db.prepare("SELECT count(*) AS n FROM exercises WHERE is_active = 1 AND gym_id IS NULL AND name_nl IS NOT NULL AND name_nl <> ''").get().n;
  const missing = db.prepare("SELECT slug FROM exercises WHERE is_active = 1 AND gym_id IS NULL AND (name_nl IS NULL OR name_nl = '')").all().map((r) => r.slug);
  const dup = db.prepare("SELECT name_nl, count(*) AS c FROM exercises WHERE is_active = 1 AND gym_id IS NULL GROUP BY lower(name_nl) HAVING c > 1").all();
  const stray = entries.filter(([slug]) => !db.prepare("SELECT 1 FROM exercises WHERE slug = ? AND is_active = 1 AND gym_id IS NULL").get(slug)).map(([s]) => s);
  console.log(`dry run on the baseline: active rows ${before}, name_nl filled ${filled}, missing ${missing.length}, duplicate name_nl ${dup.length}, JSON slugs not in baseline ${stray.length}`);
  if (missing.length) console.log('  missing:', missing.slice(0, 10).join(', '));
  if (dup.length) console.log('  duplicates:', dup.map((d) => d.name_nl).join(' | '));
  if (stray.length) console.log('  stray:', stray.slice(0, 10).join(', '));
  if (before !== filled || missing.length || dup.length || stray.length) process.exit(1);
  console.log('dry run OK');
}
