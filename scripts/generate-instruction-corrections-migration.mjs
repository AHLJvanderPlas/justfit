#!/usr/bin/env node
/**
 * Generate migrations/0130_exercise_instruction_corrections.sql from
 * scripts/fixtures/exercise-instruction-corrections.json (text 2, 2026-11-22), and rebuild the
 * review table docs/exercise-instructions.md from the baseline library (`--table`).
 *
 * Fixture: { exercises: { <slug>: { why, steps, cues, steps_nl, cues_nl } } } — the full text
 * after the correction. Each UPDATE is guarded on the text it corrects (step and cue counts and
 * the first step, as the baseline carries them); the assert fails the whole file unless every
 * listed row ends with the corrected text and every active global exercise is still complete.
 *
 * Usage:
 *   node scripts/generate-instruction-corrections-migration.mjs           # writes the migration
 *   node scripts/generate-instruction-corrections-migration.mjs --check   # … then dry-runs it
 *   node scripts/generate-instruction-corrections-migration.mjs --table   # review table from the baseline
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';
import { textErrors } from './generate-instructions-migration.mjs';

const SRC = 'scripts/fixtures/exercise-instruction-corrections.json';
const OUT = 'migrations/0130_exercise_instruction_corrections.sql';
const DOC = 'docs/exercise-instructions.md';
const STAMP = 1795392000000;   // 2026-11-22, fixed so a regeneration is byte-identical

// Wording an instruction must not carry: a medical or injury-prevention promise, or a note
// about the library itself. Shared with tests/instructionsComplete.test.js.
export const CLAIMS = [/\bDVT\b/i, /carpal/i, /sciatic/i, /disc health/i, /best-evidenced/i, /injury[- ]preventer/i,
  /main protector/i, /pain relief/i, /to see results/i, /\bthe library\b/i, /lower injury risk/i, /prevent(s|ing)? (injur|thrombos)/i];
export const claimErrors = (slug, j) => [...(j.steps ?? []), ...(j.cues ?? [])]
  .flatMap((s) => CLAIMS.filter((re) => re.test(s)).map((re) => `${slug}: "${s}" matches ${re}`));

function baselineDb() {
  const db = new DatabaseSync(':memory:');
  for (const f of ['1010_schema_training.sql', '1000_schema_core.sql', '1020_seed_exercises.sql']) db.exec(readFileSync(`migrations/baseline/${f}`, 'utf8'));
  return db;
}
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

if (import.meta.url === `file://${process.argv[1]}`) {
  const db = baselineDb();
  if (process.argv.includes('--table')) {
    const rows = db.prepare('SELECT slug, name, name_nl, category, instructions_json FROM exercises WHERE is_active = 1 AND gym_id IS NULL ORDER BY category, slug').all();
    const doc = [
      '# Exercise instructions, English and Dutch — review table',
      '',
      'GENERATED by `node scripts/generate-instruction-corrections-migration.mjs --table` from the baseline seeds:',
      'the text as production carries it after the last applied migration (0129 wrote it, 0130 corrected 44 exercises).',
      'Corrections: a new fixture and a NEW migration; never edit this file.',
      '',
      `${rows.length} exercises.`,
      '',
      ...rows.flatMap((r) => {
        const j = JSON.parse(r.instructions_json);
        return [`## ${cell(r.name_nl ?? r.name)} (\`${r.slug}\`, ${r.category})`, '', '| | English | Nederlands |', '|---|---|---|',
          ...(j.steps ?? []).map((s, i) => `| stap ${i + 1} | ${cell(s)} | ${cell(j.steps_nl?.[i])} |`),
          ...(j.cues ?? []).map((s, i) => `| tip ${i + 1} | ${cell(s)} | ${cell(j.cues_nl?.[i])} |`),
          ...(j.pregnancy_note ? [`| pregnancy_note | ${cell(j.pregnancy_note)} | ${cell(j.pregnancy_note_nl)} |`] : []), ''];
      }),
    ].join('\n');
    writeFileSync(DOC, doc);
    console.log(`wrote ${DOC} (${rows.length} exercises)`);
    process.exit(0);
  }

  const fixture = JSON.parse(readFileSync(SRC, 'utf8'));
  const errs = [];
  const rows = [];
  for (const [slug, fx] of Object.entries(fixture.exercises)) {
    const row = db.prepare('SELECT instructions_json FROM exercises WHERE slug = ? AND is_active = 1 AND gym_id IS NULL').get(slug);
    if (!row) { errs.push(`${slug}: not an active global row in the baseline`); continue; }
    const base = JSON.parse(row.instructions_json);
    errs.push(...textErrors(slug, fx, fx), ...claimErrors(slug, fx));
    if (!fx.why) errs.push(`${slug}: no why`);
    const same = ['steps', 'cues', 'steps_nl', 'cues_nl'].every((k) => JSON.stringify(base[k]) === JSON.stringify(fx[k]));
    rows.push({ slug, base, fx, same });
  }
  if (errs.length) { console.error(errs.join('\n')); process.exit(1); }
  // Applied history is frozen: once the baseline carries the corrected text, write nothing.
  if (rows.every((r) => r.same)) { console.log('the baseline already carries every correction: 0130 is applied history, nothing written'); process.exit(0); }

  const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
  const jarr = (a) => `json(${q(JSON.stringify(a))})`;
  const update = ({ slug, base, fx }) => `UPDATE exercises SET instructions_json = json_set(instructions_json, '$.steps', ${jarr(fx.steps)}, '$.cues', ${jarr(fx.cues)}, '$.steps_nl', ${jarr(fx.steps_nl)}, '$.cues_nl', ${jarr(fx.cues_nl)}), updated_at_ms = ${STAMP}`
    + ` WHERE slug = ${q(slug)} AND gym_id IS NULL AND is_active = 1 AND json_valid(instructions_json)`
    + ` AND json_array_length(instructions_json, '$.steps') = ${base.steps.length} AND json_array_length(instructions_json, '$.cues') = ${base.cues.length}`
    + ` AND json_extract(instructions_json, '$.steps[0]') = ${q(base.steps[0])};`;
  const landed = rows.map(({ slug, fx }) => `(slug = ${q(slug)} AND json_extract(instructions_json, '$.steps') = ${jarr(fx.steps)} AND json_extract(instructions_json, '$.cues_nl') = ${jarr(fx.cues_nl)})`).join('\n    OR ');

  const sql = `-- 0130 — corrections to the exercise instruction text of 0129 (text 2).
--
-- GENERATED by scripts/generate-instruction-corrections-migration.mjs from
-- scripts/fixtures/exercise-instruction-corrections.json (each entry carries its reason in \`why\`).
-- Do not hand-edit: change the JSON, regenerate, and ship the change as a NEW migration.
--
-- ${rows.length} exercises: source text that contradicted its own name, equipment or numbers, and cues
-- that made a health or injury claim. English and Dutch together. Equipment tags are untouched.
--
-- Each UPDATE only touches a row that still carries the text it corrects. The assert fails the
-- whole file unless every listed row ends with the corrected text and every active global
-- exercise still has as many Dutch steps and cues as English ones.
${rows.map(update).join('\n')}

CREATE TABLE _0130_assert (ok INTEGER NOT NULL CHECK (ok = 1)) STRICT;
INSERT INTO _0130_assert (ok) SELECT CASE WHEN (SELECT COUNT(*) FROM exercises WHERE gym_id IS NULL AND is_active = 1 AND (
    ${landed})) = ${rows.length}
  AND (SELECT COUNT(*) FROM exercises WHERE gym_id IS NULL AND is_active = 1
    AND NOT (json_valid(instructions_json)
      AND COALESCE(json_array_length(instructions_json, '$.steps_nl'), -1) = json_array_length(instructions_json, '$.steps')
      AND COALESCE(json_array_length(instructions_json, '$.cues_nl'), -1) = json_array_length(instructions_json, '$.cues'))) = 0 THEN 1 ELSE 0 END;
DROP TABLE _0130_assert;
`;
  writeFileSync(OUT, sql);
  console.log(`wrote ${OUT} (${rows.length} UPDATE statements)`);
  if (process.argv.includes('--check')) {
    db.exec(sql);
    const left = db.prepare('SELECT slug, instructions_json FROM exercises WHERE is_active = 1 AND gym_id IS NULL').all().flatMap((r) => claimErrors(r.slug, JSON.parse(r.instructions_json)));
    if (left.length) { console.error(`dry run: claims left in the library\n${left.join('\n')}`); process.exit(1); }
    console.log('dry run on the baseline OK: assert passed, no claim wording left in the library');
  }
}
