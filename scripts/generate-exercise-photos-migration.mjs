#!/usr/bin/env node
/**
 * Generate migrations/0127_exercise_photos.sql and docs/exercise-photos.md from
 * scripts/fixtures/exercise-photos.json (release media 1).
 *
 * Storage: media_json on the exercise row — {"images": ["/exercise-media/<slug>/0.jpg",
 * "/exercise-media/<slug>/1.jpg"], "source": "free-exercise-db"} — merged with json_patch into
 * whatever the row already holds, so another key (gif_url, a trainer's own media) survives and a
 * second run writes the same thing. No column, no schema change: plan steps and /api/exercises
 * read it through functions/api/_shared/exerciseMedia.js.
 *
 * The photos themselves are static files in packages/client-app/public/exercise-media, copied by
 * scripts/import-exercise-photos.mjs; scripts/media1.scan.mjs (smoke) fails when files, fixture
 * and this migration disagree.
 *
 * Checks before writing: every fixture slug is an active global row in the baseline; source ids
 * and slugs are plain names. --check also dry-runs the SQL twice on the baseline in node:sqlite.
 *
 * Usage:
 *   node scripts/generate-exercise-photos-migration.mjs           # writes migration + review table
 *   node scripts/generate-exercise-photos-migration.mjs --check   # … then dry-runs it
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
export const SRC = 'scripts/fixtures/exercise-photos.json';
export const OUT = 'migrations/0127_exercise_photos.sql';
export const DOC = 'docs/exercise-photos.md';
const STAMP = 1795305600000;   // 2026-11-21, fixed so a regeneration is byte-identical
const CATEGORIES = ['strength', 'cardio', 'mobility', 'recovery', 'skill', 'mixed'];
const rd = (f) => readFileSync(path.join(ROOT, f), 'utf8');

export const mediaPaths = (slug) => [`/exercise-media/${slug}/0.jpg`, `/exercise-media/${slug}/1.jpg`];

export function baselineDb() {
  const db = new DatabaseSync(':memory:');
  for (const f of ['1010_schema_training.sql', '1000_schema_core.sql', '1020_seed_exercises.sql']) db.exec(rd(`migrations/baseline/${f}`));
  return db;
}

/** { sql, doc, errs, count } — pure given the fixture and the baseline. */
export function render(fixture = JSON.parse(rd(SRC)), db = baselineDb()) {
  const errs = [];
  const active = db.prepare('SELECT slug, name, name_nl, category FROM exercises WHERE is_active = 1 AND gym_id IS NULL ORDER BY slug').all();
  const bySlug = new Map(active.map((r) => [r.slug, r]));
  const rows = [];
  for (const [slug, e] of Object.entries(fixture.exercises)) {
    const row = bySlug.get(slug);
    if (!/^[a-z0-9][a-z0-9-]*$/.test(slug)) errs.push(`${slug}: not a plain slug`);
    else if (!row) errs.push(`${slug}: not an active global row in the baseline`);
    if (!/^[A-Za-z0-9_,().'-]+$/.test(e.source_id ?? '')) errs.push(`${slug}: source_id "${e.source_id}" is not a plain name`);
    if (!e.source_name || !e.tier) errs.push(`${slug}: source_name and tier are required`);
    if (row) rows.push({ slug, e, row });
  }
  for (const slug of Object.keys(fixture.rejected ?? {})) if (fixture.exercises[slug]) errs.push(`${slug}: both accepted and rejected`);

  const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
  const patch = (slug) => JSON.stringify({ images: mediaPaths(slug), source: 'free-exercise-db' });
  const update = ({ slug }) => `UPDATE exercises SET media_json = json_patch(CASE WHEN json_valid(media_json) THEN media_json ELSE '{}' END, ${q(patch(slug))}), updated_at_ms = ${STAMP} WHERE slug = ${q(slug)} AND gym_id IS NULL AND is_active = 1;`;
  const slugList = rows.map((r) => q(r.slug)).join(', ');
  const perCat = CATEGORIES.map((c) => [c, rows.filter((r) => r.row.category === c).length]).filter(([, n]) => n);

  const sql = `-- 0127 — two photos (start and end position) for ${rows.length} exercises.
--
-- GENERATED by scripts/generate-exercise-photos-migration.mjs from
-- scripts/fixtures/exercise-photos.json; the review table docs/exercise-photos.md is built from the
-- same JSON. Do not hand-edit: change the JSON, re-import the photos, regenerate, and ship the
-- change as a NEW migration (this one is applied history once applied).
--
-- Release media 1: free visuals. The photos are public-domain (free-exercise-db, Unlicense) and are
-- served from this app at /exercise-media/<slug>/0.jpg and 1.jpg — no third-party origin, no CSP change.
-- Storage: media_json = {"images": [start, end], "source": "free-exercise-db"}, merged with json_patch
-- into the row's existing media_json, so other keys survive and a second run changes nothing.
-- Accepted only where the photo shows the same movement, equipment and body position.
-- Written: ${rows.length} rows (${perCat.map(([c, n]) => `${c} ${n}`).join(', ')}).
--
-- The assert at the end fails the whole file unless every listed row ends with both paths.
${rows.map(update).join('\n')}

CREATE TABLE _0127_assert (ok INTEGER NOT NULL CHECK (ok = 1)) STRICT;
INSERT INTO _0127_assert (ok) SELECT CASE WHEN (SELECT COUNT(*) FROM exercises WHERE gym_id IS NULL AND is_active = 1 AND slug IN (${slugList})
  AND json_valid(media_json)
  AND json_extract(media_json, '$.images[0]') = '/exercise-media/' || slug || '/0.jpg'
  AND json_extract(media_json, '$.images[1]') = '/exercise-media/' || slug || '/1.jpg') = ${rows.length} THEN 1 ELSE 0 END;
DROP TABLE _0127_assert;
`;

  const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
  const withPhoto = new Set(rows.map((r) => r.slug));
  const without = active.filter((r) => !withPhoto.has(r.slug));
  const doc = [
    '# Exercise photos — review table',
    '',
    `GENERATED by \`scripts/generate-exercise-photos-migration.mjs\` from \`${SRC}\` (migration \`${OUT}\`).`,
    'Corrections: edit the JSON, re-import (`node scripts/import-exercise-photos.mjs <free-exercise-db>`) and regenerate as a NEW migration; never edit this file or the SQL.',
    '',
    `Source: ${fixture.source}`,
    '',
    `Selection: ${fixture.selection}`,
    '',
    `Tier: \`exact\` / \`strong\` / \`weak\` = the automatic name match picked this photo too; \`none\` = it found nothing better than a wrong one; \`manual\` = found by hand. Every row was judged on the photos. "Start" is 0.jpg; where the source numbered them the other way round the import swaps them (\`swap\`).`,
    '',
    `**${rows.length} of ${active.length} active exercises have photos** (${perCat.map(([c, n]) => `${c} ${n}`).join(', ')}).`,
    '',
    ...CATEGORIES.flatMap((c) => {
      const rs = rows.filter((r) => r.row.category === c);
      if (!rs.length) return [];
      return [`## With photos — ${c} (${rs.length})`, '', '| Exercise | Nederlands | Source photo | Tier | Note |', '|---|---|---|---|---|',
        ...rs.map(({ slug, e, row }) => `| ${cell(row.name)} (\`${slug}\`) | ${cell(row.name_nl)} | ${cell(e.source_name)} (\`${e.source_id}\`) | ${e.tier} | ${cell([e.swap ? 'start/end swapped' : '', e.hold ? 'hold photo in both frames' : '', e.note].filter(Boolean).join('; '))} |`), ''];
    }),
    `## Without a photo (${without.length})`,
    '',
    'Grouped by category. A reason is given where a candidate photo was looked at and turned down; the rest had no candidate in the source that shows the same movement (runs, rides, marches, breathing, most cardio drills, many mobility and pregnancy exercises).',
    '',
    ...CATEGORIES.flatMap((c) => {
      const rs = without.filter((r) => r.category === c);
      if (!rs.length) return [];
      return [`### ${c} (${rs.length})`, '', ...rs.map((r) => `- ${cell(r.name)}${r.name_nl && r.name_nl !== r.name ? ` / ${cell(r.name_nl)}` : ''} (\`${r.slug}\`)${fixture.rejected?.[r.slug] ? ` — turned down: ${cell(fixture.rejected[r.slug])}` : ''}`), ''];
    }),
  ].join('\n');
  return { sql, doc, errs, count: rows.length, slugs: rows.map((r) => r.slug) };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { sql, doc, errs, count, slugs } = render();
  if (errs.length) { console.error(errs.join('\n')); process.exit(1); }
  writeFileSync(path.join(ROOT, OUT), sql);
  writeFileSync(path.join(ROOT, DOC), doc);
  console.log(`wrote ${OUT} (${count} UPDATE statements) and ${DOC}`);
  if (process.argv.includes('--check')) {
    const db = baselineDb();
    db.exec(sql);
    const first = db.prepare('SELECT slug, media_json FROM exercises WHERE media_json IS NOT NULL ORDER BY slug').all();
    db.exec(sql);   // idempotent: a second run must change nothing
    const second = db.prepare('SELECT slug, media_json FROM exercises WHERE media_json IS NOT NULL ORDER BY slug').all();
    if (first.length !== count || JSON.stringify(first) !== JSON.stringify(second)) { console.error(`dry run: ${first.length} rows carry media_json, expected ${count}, or a second run changed them`); process.exit(1); }
    const bad = first.filter((r) => !slugs.includes(r.slug));
    if (bad.length) { console.error(`dry run: unexpected rows ${bad.map((r) => r.slug).join(', ')}`); process.exit(1); }
    console.log(`dry run on the baseline OK: ${count} rows, assert passed, idempotent`);
  }
}
